UPSTREAM_COMMIT <- "e5db96d54ef5a79cbfd06e2339a3351e4583f8da"
UPSTREAM_REPO <- "https://github.com/RConsortium/pharma-skills"
UPSTREAM_COPYRIGHT <- "Jeff Dickinson, Navitas Data Sciences"

repo_root <- normalizePath(".", mustWork = TRUE)
archive_url <- paste0(
  "https://github.com/RConsortium/pharma-skills/archive/",
  UPSTREAM_COMMIT,
  ".tar.gz"
)
work_dir <- tempfile("pharma-skills-")
dir.create(work_dir)
archive_file <- file.path(work_dir, "upstream.tar.gz")
utils::download.file(archive_url, archive_file, mode = "wb", quiet = TRUE)
utils::untar(archive_file, exdir = work_dir)

source_root <- list.files(work_dir, pattern = "^pharma-skills-", full.names = TRUE)
if (length(source_root) != 1L) {
  stop("Could not identify the unpacked upstream source archive.")
}
source_root <- source_root[[1L]]
source_skill <- file.path(source_root, "admiral", "admiral-adsl")
shared_skill <- file.path(source_root, "admiral", "SKILL.md")
if (!dir.exists(source_skill) || !file.exists(shared_skill)) {
  stop("Pinned source does not contain the expected admiral skill paths.")
}

destination <- file.path(repo_root, ".agents", "skills", "admiral-adsl")
reference_dir <- file.path(destination, "references")
dir.create(reference_dir, recursive = TRUE, showWarnings = FALSE)

inventory <- data.frame(
  upstream = "admiral/SKILL.md",
  local = "references/admiral-SKILL.md",
  stringsAsFactors = FALSE
)
if (!file.copy(shared_skill, file.path(reference_dir, "admiral-SKILL.md"), overwrite = TRUE)) {
  stop("Failed to copy the shared upstream admiral skill.")
}

source_files <- list.files(
  source_skill,
  recursive = TRUE,
  full.names = TRUE,
  all.files = TRUE,
  no.. = TRUE
)
source_files <- source_files[!dir.exists(source_files)]
for (source_file in source_files) {
  relative_path <- substring(source_file, nchar(source_skill) + 2L)
  local_relative <- if (identical(relative_path, "README.md")) {
    "UPSTREAM-README.md"
  } else {
    relative_path
  }
  local_file <- file.path(destination, local_relative)
  dir.create(dirname(local_file), recursive = TRUE, showWarnings = FALSE)
  if (!file.copy(source_file, local_file, overwrite = TRUE, copy.mode = TRUE)) {
    stop("Failed to copy upstream file: ", relative_path)
  }
  inventory <- rbind(
    inventory,
    data.frame(
      upstream = file.path("admiral", "admiral-adsl", relative_path),
      local = local_relative,
      stringsAsFactors = FALSE
    )
  )
}

license_path <- file.path(destination, "LICENSE")
if (!file.exists(license_path)) {
  stop("The upstream skill LICENSE was not copied.")
}
license_text <- readLines(license_path, warn = FALSE)
copyright_line <- grep("^Copyright", license_text, value = TRUE)
copyright_holder <- if (length(copyright_line)) {
  sub("^Copyright \\(c\\) [0-9,-]+ ", "", copyright_line[[1L]])
} else {
  UPSTREAM_COPYRIGHT
}

upstream_lines <- c(
  "# Upstream record",
  "",
  paste0("- Repository: ", UPSTREAM_REPO),
  paste0("- Pinned commit: `", UPSTREAM_COMMIT, "`"),
  "- License: MIT; the upstream `LICENSE` is copied unchanged.",
  "- Derivation logic: copied without changes to derivation logic.",
  "- The shared skill is placed at `references/admiral-SKILL.md`; upstream `README.md` is retained as `UPSTREAM-README.md`.",
  "",
  "## Imported files",
  "",
  "| Upstream path | Local path |",
  "| --- | --- |",
  paste0("| `", inventory$upstream, "` | `", inventory$local, "` |"),
  "",
  "Generated by `tools/sync_upstream.R`."
)
writeLines(upstream_lines, file.path(destination, "UPSTREAM.md"))

notice_lines <- c(
  "# Third-party notices",
  "",
  "This file is generated by `tools/sync_upstream.R`. Original workshop content is covered by the repository `LICENSE`; upstream material remains governed by its own license.",
  "",
  "## Vendored file inventory",
  "",
  paste0("Upstream repository: [RConsortium/pharma-skills](", UPSTREAM_REPO, ")"),
  paste0("Pinned commit: `", UPSTREAM_COMMIT, "`"),
  "License: MIT.",
  paste0("Copyright holder: ", copyright_holder, "."),
  "",
  "| Local file | Upstream repository/path | Pinned commit | License | Copyright holder |",
  "| --- | --- | --- | --- | --- |",
  paste0(
    "| `.agents/skills/admiral-adsl/", inventory$local, "` | [`",
    inventory$upstream, "`](", UPSTREAM_REPO, "/blob/", UPSTREAM_COMMIT, "/",
    inventory$upstream, ") | `", UPSTREAM_COMMIT, "` | MIT | ",
    copyright_holder, " |"
  ),
  "",
  "## Upstream MIT license",
  "",
  paste0("Reproduced verbatim from `admiral/admiral-adsl/LICENSE` at commit `", UPSTREAM_COMMIT, "`:"),
  "",
  "```text",
  license_text,
  "```",
  ""
)
writeLines(notice_lines, file.path(repo_root, "NOTICE.md"))

message("Synced upstream admiral skill from ", UPSTREAM_COMMIT)
message("Updated ", file.path(destination, "UPSTREAM.md"), " and NOTICE.md")
unlink(work_dir, recursive = TRUE)
